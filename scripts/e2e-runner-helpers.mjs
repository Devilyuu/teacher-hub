const DATABASE_NAME = /^teacher_desk_e2e_[a-z0-9]{16,48}$/;

export function validateE2eDatabaseName(name) {
  if (!DATABASE_NAME.test(name)) {
    throw new Error("Refusing to operate on a database not generated by this E2E runner");
  }
  return name;
}

export function quoteDatabaseIdentifier(name) {
  return `"${validateE2eDatabaseName(name).replaceAll('"', '""')}"`;
}

const INHERITED_ENV = [
  "PATH", "Path", "PATHEXT", "SystemRoot", "WINDIR", "ComSpec",
  "HOME", "USERPROFILE", "HOMEDRIVE", "HOMEPATH", "TMP", "TEMP",
  "TERM", "CI", "NO_COLOR",
];

export function buildE2eChildEnv(source, generated) {
  const safe = {};
  for (const key of INHERITED_ENV) {
    if (source[key]) safe[key] = source[key];
  }
  // Generated values intentionally replace every app/E2E connection value.
  return { ...safe, ...generated };
}

export function assertNoLoadableDotenvFiles(entries) {
  const forbidden = entries.filter((entry) => {
    const name = typeof entry === "string" ? entry : entry.name;
    if (!name.toLocaleLowerCase("en-US").startsWith(".env")) return false;
    if (name !== ".env.example") return true;
    return typeof entry === "string" || !entry.isFile() || entry.isSymbolicLink();
  });
  if (forbidden.length) {
    const names = forbidden.map((entry) => typeof entry === "string" ? entry : entry.name);
    throw new Error(`E2E runner refuses dotenv file(s): ${names.join(", ")}`);
  }
}

export function containerLabelsMatch(labels, runId) {
  return labels?.["teacher-desk.e2e"] === "true" && labels?.["teacher-desk.e2e-run"] === runId;
}

const DOCKER_CONTAINER_NAME = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$/;

export async function assertExactContainerAbsent(containerName, runDocker) {
  if (!DOCKER_CONTAINER_NAME.test(containerName) || typeof runDocker !== "function") {
    throw new Error("Invalid exact container absence probe");
  }
  const escapedName = containerName.replace(/[\\^$.*+?()[\]{}|]/g, "\\$&");
  const result = await runDocker([
    "ps", "-a",
    "--filter", `name=^/${escapedName}$`,
    "--format", "{{.Names}}",
  ]);
  if (result?.code !== 0 || typeof result.stdout !== "string") {
    throw new Error("Exact container absence daemon query failed closed");
  }
  if (result.stdout.trim()) throw new Error("Exact container still exists");
  return true;
}

const POSTGRES_DATA_PATH = "/var/lib/postgresql/data";
const REQUIRED_TMPFS_OPTIONS = new Set(["rw", "nosuid", "nodev", "noexec", "size=512m"]);

function isPostgresDataPath(target) {
  return typeof target === "string"
    && (target === POSTGRES_DATA_PATH || target.startsWith(`${POSTGRES_DATA_PATH}/`));
}

export function assertPostgresTmpfsStorage(inspect) {
  const fail = () => { throw new Error("Postgres tmpfs storage inspection failed closed"); };
  if (!inspect || typeof inspect !== "object" || Array.isArray(inspect)) fail();
  if (!Array.isArray(inspect.Mounts)) fail();
  if (inspect.Binds !== null && !Array.isArray(inspect.Binds)) fail();
  if (!inspect.Tmpfs || typeof inspect.Tmpfs !== "object" || Array.isArray(inspect.Tmpfs)) fail();

  const options = inspect.Tmpfs[POSTGRES_DATA_PATH];
  if (typeof options !== "string") fail();
  const optionSet = new Set(options.split(",").map((option) => option.trim()).filter(Boolean));
  if (optionSet.size !== REQUIRED_TMPFS_OPTIONS.size) fail();
  for (const option of REQUIRED_TMPFS_OPTIONS) {
    if (!optionSet.has(option)) fail();
  }

  for (const bind of inspect.Binds ?? []) {
    if (typeof bind !== "string" || bind.includes(`:${POSTGRES_DATA_PATH}`)) fail();
  }
  for (const target of Object.keys(inspect.Tmpfs)) {
    if (isPostgresDataPath(target) && target !== POSTGRES_DATA_PATH) fail();
  }
  const protectedMounts = inspect.Mounts.filter((mount) => isPostgresDataPath(mount?.Destination));
  if (protectedMounts.some((mount) => mount.Destination !== POSTGRES_DATA_PATH)) fail();
  const targetMounts = protectedMounts.filter((mount) => mount.Destination === POSTGRES_DATA_PATH);
  if (targetMounts.length > 1) fail();
  if (targetMounts.length === 1) {
    const [mount] = targetMounts;
    if (mount.Type !== "tmpfs" || mount.Source || mount.Name || mount.RW !== true) fail();
  }
  return true;
}

export function chooseE2eFinalOutcome({
  cleanupFailures,
  signalExitCode,
  cleanupDrill,
  expectedDrillReached,
  primaryFailure,
}) {
  if (cleanupFailures.length) return { kind: "cleanup-failure", exitCode: 1 };
  if (signalExitCode !== undefined) return { kind: "signal", exitCode: signalExitCode };
  if (cleanupDrill && expectedDrillReached && !primaryFailure) {
    return { kind: "cleanup-drill-success", exitCode: undefined };
  }
  if (primaryFailure || cleanupDrill) return { kind: "failure", exitCode: 1 };
  return { kind: "success", exitCode: undefined };
}

export function extractRunnerCleanupLabels(output) {
  const labels = [];
  for (const match of output.matchAll(/^E2E cleanup failed for: (.+)$/gm)) {
    for (const label of match[1].split(",").map((value) => value.trim())) {
      if (/^[a-z0-9][a-z0-9-]*$/.test(label) && !labels.includes(label)) labels.push(label);
    }
  }
  return labels;
}

async function settleWithin(promise, timeoutMs) {
  let timer;
  try {
    return await Promise.race([
      Promise.resolve(promise).then((value) => ({ settled: true, value })),
      new Promise((resolveTimeout) => {
        timer = setTimeout(() => resolveTimeout({ settled: false }), timeoutMs);
      }),
    ]);
  } finally {
    clearTimeout(timer);
  }
}

export async function waitForPostSignalExit({
  exitPromise,
  kill,
  deadlineMs = 60_000,
  killGraceMs = 5_000,
}) {
  if (typeof kill !== "function" || deadlineMs <= 0 || killGraceMs <= 0) {
    throw new Error("Invalid post-signal exit deadline");
  }
  const beforeDeadline = await settleWithin(exitPromise, deadlineMs);
  if (beforeDeadline.settled) {
    return {
      exitCode: beforeDeadline.value,
      deadlineExceeded: false,
      killRequested: false,
      reaped: true,
    };
  }

  let killRequested = false;
  try { killRequested = kill("SIGKILL") !== false; } catch {}
  const afterKill = await settleWithin(exitPromise, killGraceMs);
  return {
    exitCode: afterKill.settled ? afterKill.value : null,
    deadlineExceeded: true,
    killRequested,
    reaped: afterKill.settled,
  };
}

export function startAbortableChild({
  signal,
  activeChildren,
  spawnChild,
  onAbort,
  prepareChild,
  beforeAbortArm,
  onArmed,
}) {
  if (signal?.aborted) throw new Error("Command interrupted before spawn");

  const child = spawnChild();
  activeChildren.add(child);
  let disposed = false;
  let abortRequested = false;
  const handleAbort = () => {
    if (abortRequested) return;
    abortRequested = true;
    onAbort(child);
  };

  try {
    prepareChild?.(child);
    beforeAbortArm?.(child);
    signal?.addEventListener("abort", handleAbort, { once: true });
    if (signal?.aborted) handleAbort();
    else onArmed?.(child);
  } catch (error) {
    signal?.removeEventListener("abort", handleAbort);
    activeChildren.delete(child);
    throw error;
  }

  return {
    child,
    dispose() {
      if (disposed) return;
      disposed = true;
      signal?.removeEventListener("abort", handleAbort);
      activeChildren.delete(child);
    },
  };
}

export async function validateOwnedTempParent(target, {
  prefix,
  markerName,
  runId,
  tempRoot = tmpdir(),
}) {
  const targetStat = await lstat(target);
  if (!targetStat.isDirectory() || targetStat.isSymbolicLink()) {
    throw new Error("Cleanup target is not an ordinary directory");
  }

  const [canonicalTarget, canonicalTempRoot] = await Promise.all([realpath(target), realpath(tempRoot)]);
  const fromTemp = relative(canonicalTempRoot, canonicalTarget);
  if (!fromTemp || fromTemp === ".." || fromTemp.startsWith(`..${sep}`) || isAbsolute(fromTemp)) {
    throw new Error("Cleanup target is outside the system temporary directory");
  }
  if (!basename(canonicalTarget).startsWith(prefix)) {
    throw new Error("Cleanup target does not have the expected run prefix");
  }

  const markerPath = join(canonicalTarget, markerName);
  const markerStat = await lstat(markerPath);
  if (!markerStat.isFile() || markerStat.isSymbolicLink()) {
    throw new Error("Cleanup marker is not an ordinary file");
  }
  const canonicalMarker = await realpath(markerPath);
  if (dirname(canonicalMarker) !== canonicalTarget || (await readFile(canonicalMarker, "utf8")) !== runId) {
    throw new Error("Cleanup marker does not belong to this run");
  }
  return canonicalTarget;
}

export function countExactCellMatches(rows, title) {
  return rows.flat().filter((value) => value === title).length;
}

/** Runs every cleanup action and returns only safe labels, never raw errors. */
export async function runCleanupSteps(steps) {
  const failures = [];
  for (const [label, action] of steps) {
    try { await action(); } catch { failures.push(label); }
  }
  return failures;
}
